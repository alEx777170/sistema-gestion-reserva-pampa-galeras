-- 3. PAQUETE TRANSACCIONAL
--------------------------------------------------------
CREATE OR REPLACE PACKAGE pkg_reservas AS
    FUNCTION cupos_disponibles(p_id_actividad IN NUMBER) RETURN NUMBER;

    PROCEDURE crear_reserva(
        p_id_reserva        IN  NUMBER,
        p_id_turista        IN  NUMBER,
        p_id_actividad      IN  NUMBER,
        p_num_personas      IN  NUMBER,
        p_id_reserva_visita OUT NUMBER);

    PROCEDURE confirmar_reserva(p_id_reserva_visita IN NUMBER);

    PROCEDURE cancelar_reserva(
        p_id_reserva_visita IN NUMBER,
        p_motivo            IN VARCHAR2 DEFAULT NULL);
END pkg_reservas;
/

CREATE OR REPLACE PACKAGE BODY pkg_reservas AS

    ----------------------------------------------------
    -- Cupos = cupo_maximo - personas en reservas activas
    ----------------------------------------------------
    FUNCTION cupos_disponibles(p_id_actividad IN NUMBER) RETURN NUMBER IS
        v_cupo      NUMBER;
        v_ocupados  NUMBER;
    BEGIN
        SELECT cupo_maximo INTO v_cupo
        FROM ACTIVIDAD WHERE id_actividad = p_id_actividad;

        SELECT NVL(SUM(num_personas), 0) INTO v_ocupados
        FROM RESERVA_VISITA
        WHERE id_actividad = p_id_actividad
          AND estado IN ('PENDIENTE','CONFIRMADA');

        RETURN v_cupo - v_ocupados;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN NULL;
    END cupos_disponibles;

    ----------------------------------------------------
    -- Auditoria (misma transaccion que la operacion)
    ----------------------------------------------------
    PROCEDURE auditar(
        p_id      IN NUMBER,
        p_oper    IN VARCHAR2,
        p_anterior IN VARCHAR2,
        p_nuevo   IN VARCHAR2) IS
    BEGIN
        INSERT INTO AUDITORIA_RESERVA (id_reserva_visita, operacion, estado_anterior, estado_nuevo)
        VALUES (p_id, p_oper, p_anterior, p_nuevo);
    END auditar;

    ----------------------------------------------------
    -- Crear reserva
    -- Tablas involucradas: RESERVA, TURISTA, ACTIVIDAD (bloqueo),
    -- RESERVA_VISITA, TURISTA_ACTIVIDAD, AUDITORIA_RESERVA
    ----------------------------------------------------
    PROCEDURE crear_reserva(
        p_id_reserva        IN  NUMBER,
        p_id_turista        IN  NUMBER,
        p_id_actividad      IN  NUMBER,
        p_num_personas      IN  NUMBER,
        p_id_reserva_visita OUT NUMBER) IS
        v_n         NUMBER;
        v_act       ACTIVIDAD%ROWTYPE;
        v_ocupados  NUMBER;
        v_monto     NUMBER(10,2);
    BEGIN
        IF p_num_personas IS NULL OR p_num_personas < 1 THEN
            RAISE_APPLICATION_ERROR(-20001, 'El numero de personas debe ser mayor a 0.');
        END IF;

        SELECT COUNT(*) INTO v_n FROM RESERVA WHERE id_reserva = p_id_reserva;
        IF v_n = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'La reserva natural indicada no existe.');
        END IF;

        SELECT COUNT(*) INTO v_n FROM TURISTA WHERE id_turista = p_id_turista;
        IF v_n = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'El turista indicado no existe.');
        END IF;

        -- Bloquea la fila de la actividad: serializa reservas concurrentes
        -- sobre la misma actividad y evita sobreventa de cupos.
        BEGIN
            SELECT * INTO v_act
            FROM ACTIVIDAD
            WHERE id_actividad = p_id_actividad
            FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20004, 'La actividad indicada no existe.');
        END;

        IF v_act.fecha_realizacion IS NULL OR v_act.fecha_realizacion < TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20005, 'La actividad no tiene una fecha futura disponible.');
        END IF;

        SELECT COUNT(*) INTO v_n
        FROM RESERVA_VISITA
        WHERE id_turista = p_id_turista
          AND id_actividad = p_id_actividad
          AND estado IN ('PENDIENTE','CONFIRMADA');
        IF v_n > 0 THEN
            RAISE_APPLICATION_ERROR(-20006, 'El turista ya tiene una reserva activa para esta actividad.');
        END IF;

        SELECT NVL(SUM(num_personas), 0) INTO v_ocupados
        FROM RESERVA_VISITA
        WHERE id_actividad = p_id_actividad
          AND estado IN ('PENDIENTE','CONFIRMADA');

        IF p_num_personas > v_act.cupo_maximo - v_ocupados THEN
            RAISE_APPLICATION_ERROR(-20007,
                'Cupos insuficientes. Disponibles: ' || (v_act.cupo_maximo - v_ocupados));
        END IF;

        v_monto := NVL(v_act.costo_soles, 0) * p_num_personas;

        INSERT INTO RESERVA_VISITA
            (id_reserva, id_turista, id_actividad, num_personas, monto_total, estado)
        VALUES
            (p_id_reserva, p_id_turista, p_id_actividad, p_num_personas, v_monto, 'PENDIENTE')
        RETURNING id_reserva_visita INTO p_id_reserva_visita;

        -- Registra/reactiva la participacion del turista en la actividad
        MERGE INTO TURISTA_ACTIVIDAD ta
        USING (SELECT p_id_turista AS id_turista,
                      p_id_actividad AS id_actividad,
                      TRUNC(v_act.fecha_realizacion) AS fecha FROM dual) s
        ON (ta.id_turista = s.id_turista
            AND ta.id_actividad = s.id_actividad
            AND ta.fecha_participacion = s.fecha)
        WHEN MATCHED THEN UPDATE SET ta.estado = 'pendiente'
        WHEN NOT MATCHED THEN INSERT (id_turista, id_actividad, fecha_participacion, estado)
             VALUES (s.id_turista, s.id_actividad, s.fecha, 'pendiente');

        auditar(p_id_reserva_visita, 'CREAR', NULL, 'PENDIENTE');

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            p_id_reserva_visita := NULL;
            RAISE;
    END crear_reserva;

    ----------------------------------------------------
    -- Confirmar reserva (PENDIENTE -> CONFIRMADA)
    ----------------------------------------------------
    PROCEDURE confirmar_reserva(p_id_reserva_visita IN NUMBER) IS
        v_rv    RESERVA_VISITA%ROWTYPE;
        v_fecha DATE;
    BEGIN
        BEGIN
            SELECT * INTO v_rv
            FROM RESERVA_VISITA
            WHERE id_reserva_visita = p_id_reserva_visita
            FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20010, 'La reserva de visita no existe.');
        END;

        IF v_rv.estado != 'PENDIENTE' THEN
            RAISE_APPLICATION_ERROR(-20011,
                'Solo se puede confirmar una reserva PENDIENTE (estado actual: ' || v_rv.estado || ').');
        END IF;

        UPDATE RESERVA_VISITA
        SET estado = 'CONFIRMADA', fecha_confirmacion = SYSTIMESTAMP
        WHERE id_reserva_visita = p_id_reserva_visita;

        SELECT TRUNC(fecha_realizacion) INTO v_fecha
        FROM ACTIVIDAD WHERE id_actividad = v_rv.id_actividad;

        UPDATE TURISTA_ACTIVIDAD
        SET estado = 'confirmado'
        WHERE id_turista = v_rv.id_turista
          AND id_actividad = v_rv.id_actividad
          AND fecha_participacion = v_fecha;

        auditar(p_id_reserva_visita, 'CONFIRMAR', 'PENDIENTE', 'CONFIRMADA');

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END confirmar_reserva;

    ----------------------------------------------------
    -- Cancelar reserva (PENDIENTE/CONFIRMADA -> CANCELADA)
    -- Libera el cupo automaticamente (el calculo excluye CANCELADA)
    ----------------------------------------------------
    PROCEDURE cancelar_reserva(
        p_id_reserva_visita IN NUMBER,
        p_motivo            IN VARCHAR2 DEFAULT NULL) IS
        v_rv    RESERVA_VISITA%ROWTYPE;
        v_fecha DATE;
    BEGIN
        BEGIN
            SELECT * INTO v_rv
            FROM RESERVA_VISITA
            WHERE id_reserva_visita = p_id_reserva_visita
            FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20010, 'La reserva de visita no existe.');
        END;

        IF v_rv.estado = 'CANCELADA' THEN
            RAISE_APPLICATION_ERROR(-20012, 'La reserva ya esta cancelada.');
        END IF;

        UPDATE RESERVA_VISITA
        SET estado = 'CANCELADA',
            fecha_cancelacion = SYSTIMESTAMP,
            motivo_cancelacion = SUBSTR(p_motivo, 1, 300)
        WHERE id_reserva_visita = p_id_reserva_visita;

        SELECT TRUNC(fecha_realizacion) INTO v_fecha
        FROM ACTIVIDAD WHERE id_actividad = v_rv.id_actividad;

        UPDATE TURISTA_ACTIVIDAD
        SET estado = 'cancelado'
        WHERE id_turista = v_rv.id_turista
          AND id_actividad = v_rv.id_actividad
          AND fecha_participacion = v_fecha;

        auditar(p_id_reserva_visita, 'CANCELAR', v_rv.estado, 'CANCELADA');

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END cancelar_reserva;

END pkg_reservas;
/

