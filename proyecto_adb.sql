CREATE OR REPLACE VIEW vw_animales_por_reserva AS
SELECT r.id_reserva,
       r.nombre AS reserva,
       h.id_hato,
       h.zona,
       a.id_animal,
       NVL(e.nombre_comun, e.nombre_cientifico) AS especie,
       e.nombre_cientifico,
       a.sexo,
       a.edad_anios,
       a.fecha_registro
FROM RESERVA r
JOIN HATO h ON h.id_reserva = r.id_reserva
JOIN ANIMAL a ON a.id_hato = h.id_hato
JOIN ESPECIE e ON e.id_especie = a.id_especie;

CREATE OR REPLACE VIEW vw_especies_conservacion AS
SELECT
    e.estado_conservacion,
    COUNT(DISTINCT e.id_especie) AS total_especies,
    COUNT(a.id_animal) AS total_individuos
FROM ESPECIE e
LEFT JOIN ANIMAL a ON e.id_especie = a.id_especie
GROUP BY e.estado_conservacion
ORDER BY
    CASE e.estado_conservacion
        WHEN 'CR' THEN 1
        WHEN 'EN' THEN 2
        WHEN 'VU' THEN 3
        WHEN 'NT' THEN 4
        ELSE 5
    END;

CREATE OR REPLACE VIEW vw_ocupacion_horario AS
SELECT rv.id_horario,
       rv.fecha_visita,
       SUM(rv.num_personas) AS personas_reservadas
FROM RESERVA_VISITA rv
WHERE rv.estado IN ('PENDIENTE','CONFIRMADA')
GROUP BY rv.id_horario, rv.fecha_visita;

CREATE OR REPLACE VIEW vw_reservas_visita AS
SELECT rv.id_reserva_visita,
       r.nombre                         AS reserva_natural,
       t.id_turista,
       t.nombre || ' ' || t.apellido    AS turista,
       t.dni,
       a.id_actividad,
       a.nombre                         AS actividad,
       a.lugar,
       rv.fecha_visita,
       h.id_horario,
       h.hora_inicio,
       rv.num_personas,
       a.costo_soles                    AS costo_unitario,
       rv.monto_total,
       rv.estado,
       rv.motivo_cancelacion,
       rv.fecha_creacion,
       rv.fecha_confirmacion,
       rv.fecha_cancelacion
FROM RESERVA_VISITA rv
JOIN RESERVA            r ON r.id_reserva   = rv.id_reserva
JOIN TURISTA            t ON t.id_turista   = rv.id_turista
JOIN HORARIO_ACTIVIDAD  h ON h.id_horario   = rv.id_horario
JOIN ACTIVIDAD          a ON a.id_actividad = h.id_actividad;

CREATE OR REPLACE VIEW vw_resumen_actividades AS
SELECT a.id_actividad,
       a.nombre,
       a.costo_soles,
       COUNT(rv.id_reserva_visita)        AS reservas_confirmadas,
       NVL(SUM(rv.num_personas), 0)       AS total_visitantes,
       NVL(SUM(rv.monto_total), 0)        AS ingresos_total
FROM ACTIVIDAD a
LEFT JOIN HORARIO_ACTIVIDAD h ON h.id_actividad = a.id_actividad
LEFT JOIN RESERVA_VISITA rv   ON rv.id_horario = h.id_horario
                             AND rv.estado = 'CONFIRMADA'
GROUP BY a.id_actividad, a.nombre, a.costo_soles;

COMMIT;

